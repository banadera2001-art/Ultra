/**
 * Procedurally generates a fully randomized foe for any battle arena.
 * Foes are never fixed: they pull randomly from the 100 diverse pets in PET_CATALOG,
 * roll a random level in the arena's difficulty tier (scaling 10 to 100),
 * have dynamic scaled combat stats, elemental affinity, and special moves!
 */
export function generateRandomEnemyForArena(arenaId: string, customLevel?: number): BattleEnemy {
  const arenaRanges: Record<string, { min: number; max: number; title: string }> = {
    'arena-plains': { min: 10, max: 24, title: 'Kapatagan' },
    'arena-forest': { min: 25, max: 44, title: 'Kagubatan' },
    'arena-volcano': { min: 45, max: 64, title: 'Bulkan' },
    'arena-ocean': { min: 65, max: 84, title: 'Karagatan' },
    'arena-summit': { min: 85, max: 100, title: 'Tuktok ng Bundok' },
  };

  const range = arenaRanges[arenaId] || { min: 10, max: 100, title: 'Arena' };
  const level = customLevel ?? (Math.floor(Math.random() * (range.max - range.min + 1)) + range.min);
  const stage = getPetStageFromLevel(level);

  // Pick a random pet definition from all 100 pets in the catalog
  const randomPet = PET_CATALOG[Math.floor(Math.random() * PET_CATALOG.length)];

  const prefixes = [
    'Ligaw na',
    'Mabangis na',
    'Mahiwagang',
    'Matapang na',
    'Dambuhalang',
    'Mabilis na',
    'Nag-aapoy na',
    'Haring',
    'Mapanirang',
    'Alamat na',
  ];
  const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
  const nameTagalog = `${prefix} ${randomPet.nameTagalog}`;
  const name = `Wild ${randomPet.name}`;

  // Stat scaling by stage and level (10 to 100)
  const stageMult = stage === 'Adult' ? 2.4 : stage === 'Teen' ? 1.6 : 1.0;
  const levelMult = 1 + (level - 1) * 0.085;

  const maxHp = Math.max(180, Math.round(randomPet.baseHp * stageMult * levelMult));
  const atk = Math.max(30, Math.round(randomPet.baseAtk * stageMult * levelMult));
  const def = Math.max(20, Math.round(randomPet.baseDef * stageMult * levelMult));
  const spd = Math.max(25, Math.round(randomPet.baseSpd * stageMult * levelMult));

  const uniqueId = `rand-foe-${arenaId}-${randomPet.id}-${Date.now().toString(36)}-${Math.floor(Math.random() * 9999)}`;

  return {
    id: uniqueId,
    name,
    nameTagalog,
    emoji: randomPet.emoji,
    element: randomPet.element as any,
    level,
    stage,
    maxHp,
    atk,
    def,
    spd,
    specialSkill: randomPet.specialSkill,
    specialSkillTagalog: randomPet.specialSkillTagalog,
    description: `Isang antas ${level} (${stage}) na ${randomPet.nameTagalog} mula sa ${range.title} na may elementong ${randomPet.element}.`,
  };
}

/**
 * Generates an array of unique randomized foes for an arena
 */
export function generateRandomEnemiesForArena(arenaId: string, count: number = 2): BattleEnemy[] {
  const foes: BattleEnemy[] = [];
  const usedEmojis = new Set<string>();

  for (let i = 0; i < count; i++) {
    let foe = generateRandomEnemyForArena(arenaId);
    let attempts = 0;
    while (usedEmojis.has(foe.emoji) && attempts < 10) {
      foe = generateRandomEnemyForArena(arenaId);
      attempts++;
    }
    usedEmojis.add(foe.emoji);
    foes.push(foe);
  }

  return foes;
}
