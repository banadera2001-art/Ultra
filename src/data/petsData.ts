/**
 * Determines stage from level (1 to 100)
 * - Level 1 to 24: Baby (Sanggol)
 * - Level 25 to 59: Teen (Kabataan)
 * - Level 60 to 100: Adult (Ganap na Alaga)
 */
export function getPetStageFromLevel(level: number): 'Baby' | 'Teen' | 'Adult' {
  if (level < 25) return 'Baby';
  if (level < 60) return 'Teen';
  return 'Adult';
}

/**
 * Calculates maximum EXP required for current level
 */
export function getMaxExpForLevel(level: number): number {
  if (level >= 100) return 1000;
  return Math.round(50 + (Math.max(1, level) - 1) * 10);
}

/**
 * Calculates food star price as pet level increases (up to Level 100)
 * Prices scale steadily with level to reward student learning efforts!
 */
export function getFoodCostForPet(baseCost: number, petLevel: number): number {
  const safeLevel = Math.max(1, Math.min(100, petLevel || 1));
  const multiplier = 1 + (safeLevel - 1) * 0.05;
  return Math.max(baseCost, Math.round(baseCost * multiplier));
}

/**
 * Calculates scaled food EXP gain for higher-level pets
 */
export function getFoodExpGainForPet(baseExp: number, petLevel: number): number {
  const safeLevel = Math.max(1, Math.min(100, petLevel || 1));
  const multiplier = 1 + (safeLevel - 1) * 0.02;
  return Math.max(baseExp, Math.round(baseExp * multiplier));
}

