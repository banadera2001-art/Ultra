/**
 * Roll a random Blox Fruit with weighted rarity probabilities
 */
export function rollRandomBloxFruit(): BloxFruit {
  const roll = Math.random() * 100;

  let chosenRarity: 'common' | 'uncommon' | 'rare' | 'legendary' | 'mythical' = 'common';
  if (roll < 45) {
    chosenRarity = 'common';
  } else if (roll < 75) {
    chosenRarity = 'uncommon';
  } else if (roll < 92) {
    chosenRarity = 'rare';
  } else if (roll < 98) {
    chosenRarity = 'legendary';
  } else {
    chosenRarity = 'mythical';
  }

  const pool = BLOX_FRUITS.filter((f) => f.rarity === chosenRarity);
  if (pool.length > 0) {
    return pool[Math.floor(Math.random() * pool.length)];
  }
  return BLOX_FRUITS[0];
}

