export const getRandomChestQuestion = (
  preferredGrade?: GradeLevel,
  preferredSubject?: QuizSubject
): ChestQuestion => {
  let pool = CHEST_QUIZ_QUESTIONS;

  if (preferredGrade) {
    const gradePool = pool.filter((q) => q.gradeLevel === preferredGrade);
    if (gradePool.length > 0) pool = gradePool;
  }

  if (preferredSubject) {
    const subjectPool = pool.filter((q) => q.subject === preferredSubject);
    if (subjectPool.length > 0) pool = subjectPool;
  }

  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
};

export const getQuestionsByGrade = (grade: GradeLevel): ChestQuestion[] => {
  return CHEST_QUIZ_QUESTIONS.filter((q) => q.gradeLevel === grade);
};

